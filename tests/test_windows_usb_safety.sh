grep -q 'B2LUI_SCALE_PERCENT=\$SCALE_PERCENT' "$ROOT/tools_winpe_ui_scale.sh"
grep -q 'LOG_PIXELS=168' "$ROOT/tools_winpe_ui_scale.sh"
