#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WIN="$ROOT/windows/b2lusb"
DSDT="$ROOT/silicium-acpi-overlay/SoCs/Samsung/S5E9820/DSDT_minimal.dsl"
PARENT_INF="$WIN/b2lusb.inf.in"
HOST_INF="$WIN/b2lusb-host.inf.in"
MAX_INF="$WIN/b2lmax77705.inf.in"

USB_BLOCK="$(sed -n '/Device (USBP)/,/^[[:space:]]*\/\/ Device (UFS0)/p' "$DSDT")"
MAX_BLOCK="$(sed -n '/Device (USBC)/,/^[[:space:]]*\/\/ Exynos9820 DWC_usb31/p' "$DSDT")"
test "$(printf '%s\n' "$USB_BLOCK" | rg -c 'Memory32Fixed')" -eq 3
printf '%s\n' "$USB_BLOCK" | grep -q '0x10C00000, 0x00010000'
printf '%s\n' "$USB_BLOCK" | grep -q '0x10B00000, 0x00000200'
printf '%s\n' "$USB_BLOCK" | grep -q '0x1586072C, 0x00000004'
printf '%s\n' "$USB_BLOCK" | grep -Fq 'Name (_HID, "BYN0002")'
printf '%s\n' "$USB_BLOCK" | grep -Fq 'Name (_HID, "BYN0003")'
printf '%s\n' "$USB_BLOCK" | grep -Fq 'Name (_DEP, Package (0x01)'
printf '%s\n' "$USB_BLOCK" | grep -Fq '\_SB.USBC'
test "$(printf '%s\n' "$USB_BLOCK" | rg -c 'Name \(_CID, "PNP0D15"\)')" -eq 1
if printf '%s\n' "$USB_BLOCK" | grep -Fq 'Name (_ADR, Zero)'; then
  echo 'HATA: statik ACPI xHCI host eski URS child _ADR alanini tasimamali' >&2
  exit 1
fi

test "$(printf '%s\n' "$MAX_BLOCK" | rg -c 'Memory32Fixed')" -eq 4
printf '%s\n' "$MAX_BLOCK" | grep -Fq 'Name (_HID, "BYN0004")'
printf '%s\n' "$MAX_BLOCK" | grep -q '0x15C00000, 0x00008000'
printf '%s\n' "$MAX_BLOCK" | grep -q '0x15D60000, 0x00001000'
printf '%s\n' "$MAX_BLOCK" | grep -q '0x15C22000, 0x00001000'
printf '%s\n' "$MAX_BLOCK" | grep -q '0x15C30000, 0x00001000'
printf '%s\n' "$MAX_BLOCK" | grep -Fq 'Name (_CCA, Zero)'
if printf '%s\n' "$USB_BLOCK" | rg -n 'Device \(URS0\)|Name \(_HID, "URS'; then
  echo 'HATA: statik HOST ACPI yolu sentetik URS aygiti tasimamali' >&2
  exit 1
fi
test "$(printf '%s\n' "$USB_BLOCK" | rg -c '0x00000111')" -eq 1
test "$(printf '%s\n' "$USB_BLOCK" | rg -c 'Name \(_CCA, Zero\)')" -eq 2
if printf '%s\n' "$USB_BLOCK" | rg -qi 'Device \(UFN0\)|0x10AE0000|0x10AF0000|0x15860704|Gpio|I2cSerialBus'; then
  echo 'HATA: USBP ilk asama allow-list disi USB3/function/Type-C kaynagi iceriyor' >&2
  exit 1
fi

grep -Fq 'ACPI\BYN0002' "$PARENT_INF"
grep -q 'KmdfLibraryVersion=1.15' "$PARENT_INF"
grep -Fq 'ACPI\BYN0003' "$HOST_INF"
grep -q 'DriverVer=09/03/2026,0.1.0.18' "$PARENT_INF"
grep -q 'DriverVer=09/03/2026,0.1.0.18' "$HOST_INF"
grep -Fq 'ACPI\BYN0004' "$MAX_INF"
grep -q 'DriverVer=09/04/2026,0.1.0.27' "$MAX_INF"
grep -q 'KmdfLibraryVersion=1.15' "$MAX_INF"
grep -qi 'Include=usbxhci.inf' "$HOST_INF"
grep -q 'Needs=Generic.Install.NT' "$HOST_INF"
grep -q 'Needs=Generic.Install.NT.Services' "$HOST_INF"
grep -q 'Needs=Generic.Install.NT.HW' "$HOST_INF"
grep -q 'b2lusbmon.sys' "$HOST_INF"
grep -q 'AddService=b2lusbmon,0x00000000' "$HOST_INF"
grep -Fq 'HKR,,UpperFilters,0x00010008,"b2lusbmon"' "$HOST_INF"
grep -q 'KmdfService=b2lusbmon' "$HOST_INF"

grep -q 'WdfDeviceInitSetCharacteristics' "$WIN/b2lusb.c"
grep -q 'FILE_AUTOGENERATED_DEVICE_NAME' "$WIN/b2lusb.c"
grep -A3 'WdfDeviceInitSetCharacteristics' "$WIN/b2lusb.c" | grep -q 'TRUE'
test "$(grep -n 'WdfDeviceInitSetCharacteristics' "$WIN/b2lusb.c" | head -n1 | cut -d: -f1)" \
  -lt "$(grep -n 'Status = WdfDeviceInitAssignSDDLString' "$WIN/b2lusb.c" | head -n1 | cut -d: -f1)"
if rg -n 'Urs|URS' "$WIN/b2lusb.c" "$WIN/b2lusb.h" "$PARENT_INF" "$HOST_INF" "$WIN/build-b2lusb.ps1"; then
  echo 'HATA: statik HOST paketi URS API/runtime bagimliligi tasimamali' >&2
  exit 1
fi
test "$(rg -c 'MmMapIoSpaceEx' "$WIN/b2lusb.c")" -eq 3
grep -q 'MemoryCount != 2' "$WIN/b2lusb.c"
grep -q 'B2lUsbMapSharedDwc3' "$WIN/b2lusb.c"
grep -q 'Address.QuadPart = B2L_DWC3_PHYSICAL_BASE' "$WIN/b2lusb.c"
grep -q 'B2L_DWC3_LENGTH' "$WIN/b2lusb.c"
grep -q 'Resource->u.Memory.Length == B2L_USBPHY_LENGTH' "$WIN/b2lusb.c"
grep -q 'Resource->u.Memory.Length == B2L_USBPMU_LENGTH' "$WIN/b2lusb.c"
if rg -n 'MmMapIoSpaceEx.*0x|SetLdo|SetBuck|S2MPS|firmware.update|flash' "$WIN"/*.[ch]; then
  echo 'HATA: Windows USB surucusu PnP kaynagini atliyor veya PMIC/firmware yaziyor' >&2
  exit 1
fi

grep -q '#define B2L_DWC3_PHYSICAL_BASE 0x10C00000ULL' "$WIN/b2lusb.h"
grep -q '#define B2L_USBPHY_PHYSICAL_BASE 0x10B00000ULL' "$WIN/b2lusb.h"
grep -q '#define B2L_USBPMU_PHYSICAL_BASE 0x1586072CULL' "$WIN/b2lusb.h"
if rg -ni '10AE0000|10AF0000|15D60000' \
  "$WIN/b2lusb.c" "$WIN/b2lusb.h" "$WIN/b2lusb_hw.c"; then
  echo 'HATA: ilk Windows USB surucusu combo PHY veya MAX77705 MMIO alanina genislemis' >&2
  exit 1
fi

grep -q 'B2L_LINK_PORT_U3_DISABLE' "$WIN/b2lusb_hw.c"
grep -q 'B2L_LINK_PORT_U2_DISABLE' "$WIN/b2lusb_hw.c"
grep -Fq 'B2L_HSP_TUNE_TXRES(1)' "$WIN/b2lusb_hw.c"
grep -Fq 'B2L_HSP_TUNE_SQRX(5)' "$WIN/b2lusb_hw.c"
grep -q 'B2L_HSP_TUNE_TXVREF(12)' "$WIN/b2lusb_hw.c"
grep -q 'B2L_HSP_TUNE_TXPREEMPA(3)' "$WIN/b2lusb_hw.c"
grep -q 'B2L_HSP_TUNE_COMPDIS(7)' "$WIN/b2lusb_hw.c"
grep -q 'B2lRequireXhciHalted' "$WIN/b2lusb_hw.c"
grep -q 'B2lStopDeviceController' "$WIN/b2lusb_hw.c"
grep -q '#define B2L_DWC3_GCTL_CORESOFTRESET' "$WIN/b2lusb_hw.c"
grep -q '#define B2L_DWC3_ROLE_RESET_MS          100UL' "$WIN/b2lusb_hw.c"
grep -q 'B2lResetDwc3RoleCore' "$WIN/b2lusb_hw.c"
grep -q 'KeDelayExecutionThread' "$WIN/b2lusb_hw.c"
grep -q '#define B2L_PHY_VERIFY_POLLS' "$WIN/b2lusb_hw.c"
grep -q 'STATUS_DEVICE_POWER_FAILURE' "$WIN/b2lusb_hw.c"
grep -q 'EvtDeviceD0Entry = B2lUsbEvtD0Entry' "$WIN/b2lusb.c"
test "$(rg -c 'Status = B2lResetDwc3RoleCore' "$WIN/b2lusb_hw.c")" -eq 1
if rg -n 'B2L_DWC3_GCTL_PRTCAP_DEVICE|B2lUsb2PhyEnable\(Context, Role\)' "$WIN/b2lusb_hw.c"; then
  echo 'HATA: statik HOST donanim yolu function-role programlamasi tasimamali' >&2
  exit 1
fi
grep -q 'B2L_USB_STATUS_CORE_RESET' "$WIN/b2lusb_public.h"
grep -q '#define B2L_USB_IOCTL_VERSION 6UL' "$WIN/b2lusb_public.h"
grep -q 'B2L_USB_STATUS_STATIC_HOST' "$WIN/b2lusb_public.h"
grep -q 'XhciUsbCmd' "$WIN/b2lusb_public.h"
grep -q 'XhciDcbaapLow' "$WIN/b2lusb_public.h"
grep -q 'XhciExtCap\[12\]' "$WIN/b2lusb_public.h"
grep -q 'IOCTL_B2L_USB_ARM_XHCI_OBSERVER' "$WIN/b2lusb_public.h"
grep -q 'B2L_XHCI_OBSERVE_SEEN_HCRST' "$WIN/b2lusb_public.h"
grep -q 'B2L_XHCI_OBSERVE_SEEN_CRCR' "$WIN/b2lusb_public.h"
grep -q 'Dwc3Gusb2PhyCfg' "$WIN/b2lusb_public.h"
grep -q 'B2L_XHCI_EXT_CAP_DWORDS' "$WIN/b2lusb_hw.c"
grep -q 'ExtCapOffset <= Context->Dwc3Length' "$WIN/b2lusb_hw.c"
grep -q 'XhciExtCap\[11\]' "$WIN/b2lusbctl.c"
grep -q 'B2L_XHCI_PORTSC_CCS' "$WIN/b2lusbctl.c"
grep -q 'B2L_XHCI_PORTSC_PED' "$WIN/b2lusbctl.c"
grep -q 'B2L_XHCI_PORTSC_PP' "$WIN/b2lusbctl.c"
grep -q 'B2L_XHCI_PORTSC_CHANGE_MASK' "$WIN/b2lusbctl.c"
grep -q 'B2lShowPortStatus(1, Status.XhciPortSc1)' "$WIN/b2lusbctl.c"
grep -q 'B2lShowPortStatus(2, Status.XhciPortSc2)' "$WIN/b2lusbctl.c"
grep -q 'b2lusbctl.exe status|observe|host' "$WIN/b2lusbctl.c"
grep -q 'B2lUsbEvtXhciObserveTimer' "$WIN/b2lusb.c"
grep -q 'B2L_XHCI_OBSERVE_WINDOW_100NS' "$WIN/b2lusb.c"
grep -q 'WDF_TIMER_CONFIG_INIT(&TimerConfig, B2lUsbEvtXhciObserveTimer)' "$WIN/b2lusb.c"
if grep -q 'WDF_TIMER_CONFIG_INIT_PERIODIC' "$WIN/b2lusb.c"; then
  echo 'HATA: observer kendi callbackinden durdurulan periodic timer kullanmamali' >&2
  exit 1
fi
grep -q 'UseHighResolutionTimer = WdfFalse' "$WIN/b2lusb.c"
grep -q 'TimerConfig.AutomaticSerialization = FALSE' "$WIN/b2lusb.c"
grep -q 'Attributes.ExecutionLevel = WdfExecutionLevelDispatch' "$WIN/b2lusb.c"
grep -q 'WdfSpinLockAcquire(Context->XhciObserveLock)' "$WIN/b2lusb.c"
TIMER_BLOCK="$(sed -n '/^B2lUsbEvtXhciObserveTimer(/,/^}/p' "$WIN/b2lusb.c")"
printf '%s\n' "$TIMER_BLOCK" | grep -q 'WdfTimerStart'
if printf '%s\n' "$TIMER_BLOCK" | grep -q 'WdfTimerStop'; then
  echo 'HATA: observer callbacki ayni timer icin concurrent stop yarismamali' >&2
  exit 1
fi
grep -q 'B2L_XHCI_OBSERVE_PERIOD_MS 20UL' "$WIN/b2lusb.h"
grep -Fq 'B2L_XHCI_OBSERVE_WINDOW_100NS (5ULL * 1000ULL * 10000ULL)' "$WIN/b2lusb.h"
OBSERVE_BLOCK="$(sed -n '/^B2lUsbHardwareObserveXhci(/,/^}/p' "$WIN/b2lusb_hw.c")"
printf '%s\n' "$OBSERVE_BLOCK" | grep -q 'B2lRead32'
if printf '%s\n' "$OBSERVE_BLOCK" | rg -n 'B2lWrite32|WRITE_REGISTER'; then
  echo 'HATA: xHCI observer salt-okuma olmali' >&2
  exit 1
fi

grep -q 'WdfFdoInitSetFilter' "$WIN/b2lusbmon.c"
grep -q 'WDF_FDO_EVENT_CALLBACKS_INIT' "$WIN/b2lusbmon.c"
grep -q 'WdfFdoInitSetEventCallbacks' "$WIN/b2lusbmon.c"
grep -q 'B2lUsbMonEvtFilterRemoveResourceRequirements' "$WIN/b2lusbmon.c"
grep -q 'B2lUsbMonEvtFilterAddResourceRequirements' "$WIN/b2lusbmon.c"
grep -q 'B2lUsbMonEvtRemoveAddedResources' "$WIN/b2lusbmon.c"
grep -q 'WdfIoResourceRequirementsListGetCount' "$WIN/b2lusbmon.c"
grep -q 'WdfIoResourceListGetDescriptor' "$WIN/b2lusbmon.c"
grep -q 'RtlIoDecodeMemIoResource' "$WIN/b2lusbmon.c"
grep -q 'B2LMonReqMemoryMinLo' "$WIN/b2lusbmon.c"
grep -q 'B2LMonReqInterruptMin' "$WIN/b2lusbmon.c"
grep -q 'B2LMonRemoveAddedSeen' "$WIN/b2lusbmon.c"
grep -q 'B2LMonAssignedRawInterruptVector' "$WIN/b2lusbmon.c"
grep -q 'B2LMonAssignedTranslatedInterruptVector' "$WIN/b2lusbmon.c"
grep -q 'B2LMonAssignedTranslatedMemoryBaseLo' "$WIN/b2lusbmon.c"
grep -q 'WdfCmResourceListGetDescriptor' "$WIN/b2lusbmon.c"
grep -q 'WdfDeviceInitAssignWdmIrpPreprocessCallback' "$WIN/b2lusbmon.c"
grep -q 'IRP_MN_START_DEVICE' "$WIN/b2lusbmon.c"
