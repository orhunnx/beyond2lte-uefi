#include <initguid.h>
#include "b2lusb.h"

static NTSTATUS
B2lUsbMapResource(
    PB2L_USB_CONTEXT Context,
    PCM_PARTIAL_RESOURCE_DESCRIPTOR Resource
    )
{
    ULONGLONG Start;
    PUCHAR Mapping;

    if (Resource->Type != CmResourceTypeMemory) {
        return STATUS_SUCCESS;
    }

    Start = (ULONGLONG)Resource->u.Memory.Start.QuadPart;
    Mapping = NULL;
    if ((Start == B2L_USBPHY_PHYSICAL_BASE) &&
               (Resource->u.Memory.Length == B2L_USBPHY_LENGTH) &&
               (Context->PhyRegisters == NULL)) {
        Mapping = (PUCHAR)MmMapIoSpaceEx(
            Resource->u.Memory.Start,
            Resource->u.Memory.Length,
            PAGE_READWRITE | PAGE_NOCACHE
            );
        Context->PhyRegisters = Mapping;
        Context->PhyLength = Resource->u.Memory.Length;
    } else if ((Start == B2L_USBPMU_PHYSICAL_BASE) &&
               (Resource->u.Memory.Length == B2L_USBPMU_LENGTH) &&
               (Context->PmuUsbPhy == NULL)) {
        Mapping = (PUCHAR)MmMapIoSpaceEx(
            Resource->u.Memory.Start,
            Resource->u.Memory.Length,
            PAGE_READWRITE | PAGE_NOCACHE
            );
        Context->PmuUsbPhy = (PULONG)Mapping;
    } else {
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    }

    return (Mapping != NULL) ? STATUS_SUCCESS : STATUS_INSUFFICIENT_RESOURCES;
}

static NTSTATUS
B2lUsbMapSharedDwc3(
    PB2L_USB_CONTEXT Context
    )
{
    PHYSICAL_ADDRESS Address;

    if (Context->Dwc3Registers != NULL) {
        return STATUS_SUCCESS;
    }

    // The ACPI host child exclusively owns this range for PnP arbitration.
    // Its parent maps the same verified DWC3 page only to complete the SoC
    // PHY/core HOST handoff before Windows starts that child.
    Address.QuadPart = B2L_DWC3_PHYSICAL_BASE;
    Context->Dwc3Registers = (PUCHAR)MmMapIoSpaceEx(
        Address,
        B2L_DWC3_LENGTH,
        PAGE_READWRITE | PAGE_NOCACHE
        );
    if (Context->Dwc3Registers == NULL) {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    Context->Dwc3Length = B2L_DWC3_LENGTH;
    return STATUS_SUCCESS;
}

static VOID
B2lUsbUnmapResources(
    PB2L_USB_CONTEXT Context
    )
{
    if (Context->PmuUsbPhy != NULL) {
        MmUnmapIoSpace(Context->PmuUsbPhy, B2L_USBPMU_LENGTH);
        Context->PmuUsbPhy = NULL;
    }
    if (Context->PhyRegisters != NULL) {
        MmUnmapIoSpace(Context->PhyRegisters, Context->PhyLength);
        Context->PhyRegisters = NULL;
        Context->PhyLength = 0;
    }
    if (Context->Dwc3Registers != NULL) {
        MmUnmapIoSpace(Context->Dwc3Registers, Context->Dwc3Length);
        Context->Dwc3Registers = NULL;
        Context->Dwc3Length = 0;
    }
}

NTSTATUS
DriverEntry(
    PDRIVER_OBJECT DriverObject,
    PUNICODE_STRING RegistryPath
    )
{
    WDF_DRIVER_CONFIG Config;
    WDF_OBJECT_ATTRIBUTES Attributes;

    WDF_DRIVER_CONFIG_INIT(&Config, B2lUsbEvtDeviceAdd);
    WDF_OBJECT_ATTRIBUTES_INIT(&Attributes);
    return WdfDriverCreate(
        DriverObject,
        RegistryPath,
        &Attributes,
        &Config,
        WDF_NO_HANDLE
        );
}

NTSTATUS
B2lUsbEvtDeviceAdd(
    WDFDRIVER Driver,
    PWDFDEVICE_INIT DeviceInit
    )
{
    WDF_OBJECT_ATTRIBUTES Attributes;
    WDF_PNPPOWER_EVENT_CALLBACKS PowerCallbacks;
    WDF_IO_QUEUE_CONFIG QueueConfig;
    WDF_TIMER_CONFIG TimerConfig;
    WDFDEVICE Device;
    PB2L_USB_CONTEXT Context;
    WDFWAITLOCK Lock;
    WDFSPINLOCK SpinLock;
    UNICODE_STRING Sddl;
    NTSTATUS Status;

    UNREFERENCED_PARAMETER(Driver);

    // WdfDeviceInitAssignSDDLString rejects an unnamed device.  Keep the
    // platform FDO out of the legacy named-device namespace while giving WDF
    // object name to which the LocalSystem/Administrators ACL can be applied.
    WdfDeviceInitSetCharacteristics(
        DeviceInit,
        FILE_AUTOGENERATED_DEVICE_NAME,
        TRUE
        );

    WDF_PNPPOWER_EVENT_CALLBACKS_INIT(&PowerCallbacks);
    PowerCallbacks.EvtDevicePrepareHardware = B2lUsbEvtPrepareHardware;
    PowerCallbacks.EvtDeviceReleaseHardware = B2lUsbEvtReleaseHardware;
    PowerCallbacks.EvtDeviceD0Entry = B2lUsbEvtD0Entry;
    PowerCallbacks.EvtDeviceD0Exit = B2lUsbEvtD0Exit;
    WdfDeviceInitSetPnpPowerEventCallbacks(DeviceInit, &PowerCallbacks);

    // Only LocalSystem and administrators may request a role transition.
    RtlInitUnicodeString(
        &Sddl,
        L"D:P(A;;GA;;;SY)(A;;GA;;;BA)"
        );
    Status = WdfDeviceInitAssignSDDLString(DeviceInit, &Sddl);
    if (!NT_SUCCESS(Status)) {
        return Status;
    }

    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&Attributes, B2L_USB_CONTEXT);
    Attributes.ExecutionLevel = WdfExecutionLevelPassive;
    Status = WdfDeviceCreate(&DeviceInit, &Attributes, &Device);
    if (!NT_SUCCESS(Status)) {
        return Status;
    }

    Context = B2lUsbGetContext(Device);
    RtlZeroMemory(Context, sizeof(*Context));
    Context->Device = Device;
    Context->RequestedRole = B2lUsbRoleNone;
    Context->CurrentRole = B2lUsbRoleNone;
    Context->LastRoleStatus = STATUS_DEVICE_NOT_READY;

    WDF_OBJECT_ATTRIBUTES_INIT(&Attributes);
    Attributes.ParentObject = Device;
    Status = WdfWaitLockCreate(&Attributes, &Lock);
    if (!NT_SUCCESS(Status)) {
        return Status;
    }
    Context->RoleLock = Lock;

    WDF_OBJECT_ATTRIBUTES_INIT(&Attributes);
    Attributes.ParentObject = Device;
    Status = WdfSpinLockCreate(&Attributes, &SpinLock);
    if (!NT_SUCCESS(Status)) {
        return Status;
    }
    Context->XhciObserveLock = SpinLock;

    WDF_TIMER_CONFIG_INIT(&TimerConfig, B2lUsbEvtXhciObserveTimer);
    TimerConfig.AutomaticSerialization = FALSE;
    TimerConfig.UseHighResolutionTimer = WdfTrue;
    WDF_OBJECT_ATTRIBUTES_INIT(&Attributes);
    Attributes.ParentObject = Device;
    Attributes.ExecutionLevel = WdfExecutionLevelDispatch;
    Status = WdfTimerCreate(
        &TimerConfig,
        &Attributes,
        &Context->XhciObserveTimer
        );
    if (!NT_SUCCESS(Status)) {
        return Status;
    }

    Status = WdfDeviceCreateDeviceInterface(
        Device,
        &GUID_DEVINTERFACE_B2L_USB,
        NULL
        );
    if (!NT_SUCCESS(Status)) {
        return Status;
    }

    WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(
        &QueueConfig,
        WdfIoQueueDispatchSequential
        );
    QueueConfig.EvtIoDeviceControl = B2lUsbEvtIoDeviceControl;
    Status = WdfIoQueueCreate(
        Device,
        &QueueConfig,
        WDF_NO_OBJECT_ATTRIBUTES,
        WDF_NO_HANDLE
        );
    if (!NT_SUCCESS(Status)) {
        return Status;
    }

    return STATUS_SUCCESS;
}

NTSTATUS
B2lUsbEvtPrepareHardware(
    WDFDEVICE Device,
    WDFCMRESLIST ResourcesRaw,
    WDFCMRESLIST ResourcesTranslated
    )
{
    PB2L_USB_CONTEXT Context;
    PCM_PARTIAL_RESOURCE_DESCRIPTOR Resource;
    ULONG Count;
    ULONG Index;
    ULONG MemoryCount;
    NTSTATUS Status;

    UNREFERENCED_PARAMETER(ResourcesRaw);

    Context = B2lUsbGetContext(Device);
    Status = B2lUsbMapSharedDwc3(Context);
    if (!NT_SUCCESS(Status)) {
        goto Failure;
    }

    Count = WdfCmResourceListGetCount(ResourcesTranslated);
    MemoryCount = 0;
    for (Index = 0; Index < Count; ++Index) {
        Resource = WdfCmResourceListGetDescriptor(ResourcesTranslated, Index);
        if (Resource == NULL) {
            Status = STATUS_DEVICE_CONFIGURATION_ERROR;
            goto Failure;
        }
        if (Resource->Type == CmResourceTypeMemory) {
            ++MemoryCount;
            Status = B2lUsbMapResource(Context, Resource);
            if (!NT_SUCCESS(Status)) {
                goto Failure;
            }
        } else if (Resource->Type != CmResourceTypeDevicePrivate) {
            Status = STATUS_DEVICE_CONFIGURATION_ERROR;
            goto Failure;
        }
    }

    if ((MemoryCount != 2) ||
        (Context->Dwc3Registers == NULL) ||
        (Context->PhyRegisters == NULL) ||
        (Context->PmuUsbPhy == NULL)) {
        Status = STATUS_DEVICE_CONFIGURATION_ERROR;
        goto Failure;
    }

    Status = B2lUsbHardwareValidate(Context);
    if (!NT_SUCCESS(Status)) {
        goto Failure;
    }

    Context->RequestedRole = B2lUsbRoleHost;
    Status = B2lUsbHardwareSetRole(Context, B2lUsbRoleHost);
    Context->LastRoleStatus = Status;
    if (!NT_SUCCESS(Status)) {
        goto Failure;
    }
    Context->HardwareReady = TRUE;
    Context->CurrentRole = B2lUsbRoleHost;
    return STATUS_SUCCESS;

Failure:
    B2lUsbUnmapResources(Context);
    return Status;
}

NTSTATUS
B2lUsbEvtReleaseHardware(
    WDFDEVICE Device,
    WDFCMRESLIST ResourcesTranslated
    )
{
    PB2L_USB_CONTEXT Context;

    UNREFERENCED_PARAMETER(ResourcesTranslated);

    Context = B2lUsbGetContext(Device);
    WdfTimerStop(Context->XhciObserveTimer, TRUE);
    WdfWaitLockAcquire(Context->RoleLock, NULL);
    WdfSpinLockAcquire(Context->XhciObserveLock);
    Context->XhciObserveFlags &= ~B2L_XHCI_OBSERVE_ACTIVE;
    WdfSpinLockRelease(Context->XhciObserveLock);
    Context->HardwareReady = FALSE;
    Context->CurrentRole = B2lUsbRoleNone;
    B2lUsbUnmapResources(Context);
    WdfWaitLockRelease(Context->RoleLock);
    return STATUS_SUCCESS;
}

VOID
B2lUsbEvtXhciObserveTimer(
    WDFTIMER Timer
    )
{
    WDFDEVICE Device;
    PB2L_USB_CONTEXT Context;
    BOOLEAN Rearm;

    Device = (WDFDEVICE)WdfTimerGetParentObject(Timer);
    Context = B2lUsbGetContext(Device);
    Rearm = FALSE;

    WdfSpinLockAcquire(Context->XhciObserveLock);
    if ((Context->XhciObserveFlags & B2L_XHCI_OBSERVE_ACTIVE) != 0) {
        if (KeQueryInterruptTime() >= Context->XhciObserveDeadline) {
            Context->XhciObserveFlags &= ~B2L_XHCI_OBSERVE_ACTIVE;
        } else {
            B2lUsbHardwareObserveXhci(Context);
            Rearm = TRUE;
        }
    }
    WdfSpinLockRelease(Context->XhciObserveLock);

    if (Rearm) {
        (VOID)WdfTimerStart(
            Timer,
            WDF_REL_TIMEOUT_IN_MS(B2L_XHCI_OBSERVE_PERIOD_MS)
            );
    }
}

static NTSTATUS
B2lUsbArmXhciObserver(
    PB2L_USB_CONTEXT Context
    )
{
    NTSTATUS Status;

    (VOID)WdfTimerStop(Context->XhciObserveTimer, TRUE);
    WdfWaitLockAcquire(Context->RoleLock, NULL);
    Status = Context->HardwareReady ? STATUS_SUCCESS : STATUS_DEVICE_NOT_READY;
    if (NT_SUCCESS(Status)) {
        WdfSpinLockAcquire(Context->XhciObserveLock);
        Context->XhciObserveDeadline = KeQueryInterruptTime() +
            B2L_XHCI_OBSERVE_WINDOW_100NS;
        Context->XhciObserveFlags = B2L_XHCI_OBSERVE_ARMED |
            B2L_XHCI_OBSERVE_ACTIVE;
        Context->XhciObserveSamples = 0;
        Context->XhciObserveTransitions = 0;
        Context->XhciObserveFirstUsbCmd = 0;
        Context->XhciObserveFirstUsbSts = 0;
        Context->XhciObserveLastUsbCmd = 0;
        Context->XhciObserveLastUsbSts = 0;
        Context->XhciObserveUsbCmdOr = 0;
        Context->XhciObserveUsbStsOr = 0;
        Context->XhciObserveCrcrLow = 0;
        Context->XhciObserveCrcrHigh = 0;
        Context->XhciObserveDcbaapLow = 0;
        Context->XhciObserveDcbaapHigh = 0;
        Context->XhciObserveConfig = 0;
        B2lUsbHardwareObserveXhci(Context);
        WdfSpinLockRelease(Context->XhciObserveLock);
    }
    WdfWaitLockRelease(Context->RoleLock);

    if (NT_SUCCESS(Status)) {
        (VOID)WdfTimerStart(
            Context->XhciObserveTimer,
            WDF_REL_TIMEOUT_IN_MS(B2L_XHCI_OBSERVE_PERIOD_MS)
            );
    }
    return Status;
}

NTSTATUS
B2lUsbEvtD0Entry(
    WDFDEVICE Device,
    WDF_POWER_DEVICE_STATE PreviousState
    )
{
    PB2L_USB_CONTEXT Context;
    NTSTATUS Status;

    UNREFERENCED_PARAMETER(PreviousState);

    Context = B2lUsbGetContext(Device);
    WdfWaitLockAcquire(Context->RoleLock, NULL);
    Context->RequestedRole = B2lUsbRoleHost;
    Status = Context->HardwareReady ?
        B2lUsbHardwareSetRole(Context, B2lUsbRoleHost) :
        STATUS_DEVICE_NOT_READY;
    Context->LastRoleStatus = Status;
    if (NT_SUCCESS(Status)) {
        Context->CurrentRole = B2lUsbRoleHost;
    }
    WdfWaitLockRelease(Context->RoleLock);
    return Status;
}

NTSTATUS
B2lUsbEvtD0Exit(
    WDFDEVICE Device,
    WDF_POWER_DEVICE_STATE TargetState
    )
{
    PB2L_USB_CONTEXT Context;
    NTSTATUS Status;

    UNREFERENCED_PARAMETER(TargetState);

    Context = B2lUsbGetContext(Device);
    WdfWaitLockAcquire(Context->RoleLock, NULL);
    Status = Context->HardwareReady ?
        B2lUsbHardwareSetRole(Context, B2lUsbRoleNone) : STATUS_SUCCESS;
    if (NT_SUCCESS(Status)) {
        Context->CurrentRole = B2lUsbRoleNone;
    }
    Context->LastRoleStatus = Status;
    WdfWaitLockRelease(Context->RoleLock);
    return Status;
}

VOID
B2lUsbEvtIoDeviceControl(
    WDFQUEUE Queue,
    WDFREQUEST Request,
    size_t OutputBufferLength,
    size_t InputBufferLength,
    ULONG IoControlCode
    )
{
    WDFDEVICE Device;
    PB2L_USB_CONTEXT Context;
    B2L_USB_SET_ROLE_INPUT *Input;
    B2L_USB_STATUS *Output;
    size_t Length;
    NTSTATUS Status;

    UNREFERENCED_PARAMETER(OutputBufferLength);
    UNREFERENCED_PARAMETER(InputBufferLength);

    Device = WdfIoQueueGetDevice(Queue);
    Context = B2lUsbGetContext(Device);
    Length = 0;

    if (IoControlCode == IOCTL_B2L_USB_GET_STATUS) {
        Status = WdfRequestRetrieveOutputBuffer(
            Request,
            sizeof(*Output),
            (PVOID *)&Output,
            NULL
            );
        if (NT_SUCCESS(Status)) {
            RtlZeroMemory(Output, sizeof(*Output));
            Output->Version = B2L_USB_IOCTL_VERSION;
            Output->Size = (ULONG)sizeof(*Output);
            WdfWaitLockAcquire(Context->RoleLock, NULL);
            Output->RequestedRole = Context->RequestedRole;
            Output->CurrentRole = Context->CurrentRole;
            Output->LastRoleStatus = Context->LastRoleStatus;
            B2lUsbHardwareGetStatus(Context, Output);
            WdfWaitLockRelease(Context->RoleLock);
            Length = sizeof(*Output);
        }
        WdfRequestCompleteWithInformation(Request, Status, Length);
        return;
    }

    if (IoControlCode == IOCTL_B2L_USB_ARM_XHCI_OBSERVER) {
        Status = B2lUsbArmXhciObserver(Context);
        WdfRequestComplete(Request, Status);
        return;
    }

    if (IoControlCode != IOCTL_B2L_USB_SET_ROLE) {
        WdfRequestComplete(Request, STATUS_INVALID_DEVICE_REQUEST);
        return;
    }

    Status = WdfRequestRetrieveInputBuffer(
        Request,
        sizeof(*Input),
        (PVOID *)&Input,
        NULL
        );
    if (!NT_SUCCESS(Status)) {
        WdfRequestComplete(Request, Status);
        return;
    }
    if ((Input->Version != B2L_USB_IOCTL_VERSION) ||
        (Input->Size != (ULONG)sizeof(*Input)) ||
        (Input->Role > B2lUsbRoleDevice)) {
        WdfRequestComplete(Request, STATUS_INVALID_PARAMETER);
        return;
    }

    WdfWaitLockAcquire(Context->RoleLock, NULL);
    if (Input->Role != B2lUsbRoleHost) {
        Status = STATUS_NOT_SUPPORTED;
    } else if (!Context->HardwareReady) {
        Status = STATUS_DEVICE_NOT_READY;
    } else {
        Context->RequestedRole = B2lUsbRoleHost;
        Status = B2lUsbHardwareSetRole(Context, B2lUsbRoleHost);
        Context->LastRoleStatus = Status;
        if (NT_SUCCESS(Status)) {
            Context->CurrentRole = B2lUsbRoleHost;
        }
    }
    WdfWaitLockRelease(Context->RoleLock);
    WdfRequestComplete(Request, Status);
}
